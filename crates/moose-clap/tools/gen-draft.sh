#!/usr/bin/env bash
# Regenerate src/draft.rs: Rust bindings for the CLAP draft extensions and
# draft factories, from the pinned free-audio/clap tag. Stable types come
# from clap-sys (identical ABI through 1.2.10), so only draft headers are
# generated. Needs `bindgen` and libclang.
set -euo pipefail
TAG=1.2.10
here=$(cd "$(dirname "$0")/.." && pwd)
src=$(mktemp -d "${TMPDIR:-/data/dev/workspace/BuildScratch}/clap-XXXXXX")
trap 'rm -rf "$src"' EXIT
git clone -q --depth 1 --branch "$TAG" https://github.com/free-audio/clap.git "$src/clap"
printf '#include "clap/all.h"\n' > "$src/all.h"
{
  cat <<HDR
//! CLAP $TAG draft extensions and factories (\`clap-draft\` feature).
//! Generated by \`tools/gen-draft.sh\` with bindgen; do not edit. Stable
//! types are clap-sys's, which match the $TAG headers.
#![allow(non_camel_case_types, non_upper_case_globals, dead_code, clippy::all, clippy::pedantic)]

use clap_sys::color::clap_color as clap_color_t;
use clap_sys::events::{clap_event_header as clap_event_header_t, clap_input_events as clap_input_events_t, clap_output_events as clap_output_events_t};
use clap_sys::fixedpoint::clap_beattime;
use clap_sys::host::clap_host as clap_host_t;
use clap_sys::id::clap_id;
use clap_sys::plugin::{clap_plugin, clap_plugin as clap_plugin_t};
use clap_sys::stream::{clap_istream as clap_istream_t, clap_ostream as clap_ostream_t};
use clap_sys::universal_plugin_id::clap_universal_plugin_id as clap_universal_plugin_id_t;
use clap_sys::version::clap_version as clap_version_t;

HDR
  bindgen "$src/all.h" --allowlist-file '.*/(ext|factory)/draft/.*' --no-recursive-allowlist \
    --no-layout-tests --no-doc-comments --generate-cstr --default-macro-constant-type signed \
    -- -I"$src/clap/include"
} > "$here/src/draft.rs"
rustfmt --edition 2024 "$here/src/draft.rs"
